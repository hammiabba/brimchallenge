"""
ReferenceRepository: the read-only view of master data that extraction, coding and
controls depend on.

Owner: Person A (interface), DB team (DB-backed implementation).
Returns pandas DataFrames whose columns match the dataset CSV headers exactly, with
**every value as a string** ("" for missing). Keeping raw strings means IDs like bank
institution "004" or transit "05541" never lose their leading zeros. Callers convert to
Decimal/date at the point of use.

To change safely: adding a method is fine. Renaming or removing one breaks callers in
three folders, so announce it first.
"""
from __future__ import annotations

from datetime import date
from decimal import Decimal
from typing import Protocol

import pandas as pd


class ReferenceRepository(Protocol):
    def vendors(self) -> pd.DataFrame: ...
    def vendor(self, vendor_id: str) -> dict | None: ...
    def invoices(self) -> pd.DataFrame: ...
    def invoice_lines(self) -> pd.DataFrame: ...
    def payments(self) -> pd.DataFrame: ...
    def tax_codes(self) -> pd.DataFrame: ...
    def fx_rates(self) -> pd.DataFrame: ...
    def contracts(self) -> pd.DataFrame: ...
    def purchase_orders(self) -> pd.DataFrame: ...
    def users(self) -> pd.DataFrame: ...
    def departments(self) -> pd.DataFrame: ...
    def gl_accounts(self) -> pd.DataFrame: ...
    def card_transactions(self) -> pd.DataFrame: ...
    def bank_change_history(self) -> pd.DataFrame: ...
    def approval_policies(self) -> pd.DataFrame: ...

    def fx_rate(self, on: date) -> Decimal | None:
        """USD→CAD rate for `on`, or the closest earlier date if that day is missing (weekends)."""
        ...
